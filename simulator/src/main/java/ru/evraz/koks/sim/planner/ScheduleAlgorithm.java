package ru.evraz.koks.sim.planner;

/**
 * Алгоритм формирования расписания (docs/05 §5). Реализации отличаются
 * <b>только назначением времён</b>: порядок печей у всех общий — он приходит
 * во входе и не пересобирается (ограничение серийности H1).
 *
 * <p>Так алгоритмы прогоняются в цикле на одном входе — это и есть
 * сравнение алгоритмов, которого требует методичка.
 */
public interface ScheduleAlgorithm {

    /** Код алгоритма для API и записей прогона: b1_fifo / b2_idle / b3_smooth. */
    String code();

    /** Отображаемое имя: «B1 FIFO», «B2 idle», «B3 smooth». */
    String title();

    /**
     * Плановое время начала выталкивания для каждой выдачи из входа, по порядку.
     * Результат не убывает и не раньше физического предела готовности печи
     * и машин — план реализуем.
     */
    double[] build(ScheduleInput input);

    /** План не может убывать: симулятор принимает только неубывающие времена. */
    static double[] monotone(double[] plan) {
        for (int i = 1; i < plan.length; i++)
            plan[i] = Math.max(plan[i], plan[i - 1]);
        return plan;
    }
}
